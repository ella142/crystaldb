from __future__ import annotations

import argparse
import csv
import json
import re
from pathlib import Path
from typing import Any

from bson import ObjectId
from bson.json_util import dumps
from pymongo import MongoClient


PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_URI = "mongodb://localhost:27017"
DEFAULT_DATABASE = "opxrd"
COLLECTION = "multiphase_formula_candidates_v1"
DEFAULT_OUTPUT_DIR = PROJECT_ROOT / "data" / "multi-phase"
JSONL_NAME = "opxrd_multiphase_candidates_v1.jsonl"
CSV_NAME = "opxrd_multiphase_candidates_v1.csv"
MANIFEST_NAME = "opxrd_multiphase_export_manifest_v1.json"
RECORD_DIR_NAME = "json"

SAFE_NAME_RE = re.compile(r"[^A-Za-z0-9._-]+")


def json_default(value: Any) -> Any:
    if isinstance(value, ObjectId):
        return str(value)
    raise TypeError(f"Cannot serialize {type(value)!r}")


def safe_record_filename(source_record_id: str, object_id: ObjectId) -> str:
    stem = SAFE_NAME_RE.sub("__", source_record_id).strip("._")
    if not stem:
        stem = "record"
    return f"{stem}__{object_id}.json"


def compact_csv_row(doc: dict[str, Any]) -> dict[str, Any]:
    detection = doc.get("phase_detection") or {}
    summary = doc.get("source_document_summary") or {}
    metadata = summary.get("metadata") or {}
    import_meta = summary.get("import_meta") or {}
    return {
        "_id": str(doc["_id"]),
        "source_record_id": doc.get("source_record_id"),
        "source_collection": doc.get("source_collection"),
        "source": doc.get("source"),
        "source_provider": summary.get("source_provider"),
        "record_key": summary.get("record_key"),
        "pattern_name": summary.get("pattern_name"),
        "phase_count": summary.get("phase_count"),
        "is_mixed_phase": summary.get("is_mixed_phase"),
        "formula_count": detection.get("formula_count"),
        "distinct_formula_count": detection.get("distinct_formula_count"),
        "formulas": json.dumps(
            detection.get("formulas", []),
            ensure_ascii=True,
            separators=(",", ":"),
        ),
        "classification_status": detection.get("classification_status"),
        "institution": metadata.get("institution"),
        "original_file_format": metadata.get("original_file_format"),
        "source_relative_path": import_meta.get("relative_path"),
    }


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Export lightweight OPXRD multiphase candidate documents."
    )
    parser.add_argument("--uri", default=DEFAULT_URI)
    parser.add_argument("--database", default=DEFAULT_DATABASE)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Allow overwriting files generated by this exporter.",
    )
    args = parser.parse_args()

    output_dir = args.output_dir.resolve()
    record_dir = output_dir / RECORD_DIR_NAME
    output_dir.mkdir(parents=True, exist_ok=True)
    record_dir.mkdir(parents=True, exist_ok=True)

    output_paths = [
        output_dir / JSONL_NAME,
        output_dir / CSV_NAME,
        output_dir / MANIFEST_NAME,
    ]
    if not args.overwrite:
        existing = [path for path in output_paths if path.exists()]
        existing_records = list(record_dir.glob("*.json"))
        if existing or existing_records:
            names = [str(path) for path in existing]
            names.extend(str(path) for path in existing_records[:5])
            raise SystemExit(
                "Output already exists; rerun with --overwrite. "
                + ", ".join(names)
            )

    client = MongoClient(args.uri, serverSelectionTimeoutMS=10_000)
    collection = client[args.database][COLLECTION]
    documents = list(
        collection.find(
            {},
            {
                "_id": 1,
                "source_collection": 1,
                "source_record_id": 1,
                "source": 1,
                "phase_detection": 1,
                "phase_original": 1,
                "source_document_summary": 1,
            },
        ).sort("source_record_id", 1)
    )

    if len(documents) != 346:
        raise RuntimeError(
            f"Expected 346 candidate documents, found {len(documents)}."
        )

    statuses = {
        (doc.get("phase_detection") or {}).get("classification_status")
        for doc in documents
    }
    if statuses != {"confirmed_multiple_formulas"}:
        raise RuntimeError(f"Unexpected classification statuses: {statuses}")

    jsonl_path = output_dir / JSONL_NAME
    with jsonl_path.open("w", encoding="utf-8", newline="\n") as handle:
        for doc in documents:
            handle.write(dumps(doc))
            handle.write("\n")

    fieldnames = list(compact_csv_row(documents[0]).keys())
    csv_path = output_dir / CSV_NAME
    with csv_path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        for doc in documents:
            writer.writerow(compact_csv_row(doc))

    record_paths: list[str] = []
    for doc in documents:
        source_record_id = str(doc["source_record_id"])
        filename = safe_record_filename(source_record_id, doc["_id"])
        record_path = record_dir / filename
        with record_path.open("w", encoding="utf-8", newline="\n") as handle:
            handle.write(dumps(doc))
            handle.write("\n")
        record_paths.append(str(record_path))

    manifest = {
        "database": args.database,
        "source_collection": "patterns",
        "source_candidate_collection": COLLECTION,
        "output_directory": str(output_dir),
        "record_directory": str(record_dir),
        "documents_exported": len(documents),
        "classification_statuses": sorted(statuses),
        "format": {
            "jsonl": str(jsonl_path),
            "csv": str(csv_path),
            "per_record_json": f"{record_dir}\\*.json",
        },
        "content_policy": {
            "includes": [
                "_id",
                "source_record_id",
                "phase_detection",
                "phase_original",
                "source_document_summary",
            ],
            "excludes_complete_diffraction_arrays": True,
            "excluded_fields": [
                "two_theta",
                "intensity",
                "intensities",
                "xrd",
            ],
            "cif_exported": False,
        },
        "record_files": record_paths,
    }
    manifest_path = output_dir / MANIFEST_NAME
    with manifest_path.open("w", encoding="utf-8") as handle:
        json.dump(manifest, handle, ensure_ascii=True, indent=2)
        handle.write("\n")

    print(
        json.dumps(
            {
                "output_directory": str(output_dir),
                "documents_exported": len(documents),
                "jsonl": str(jsonl_path),
                "csv": str(csv_path),
                "per_record_json_count": len(record_paths),
                "manifest": str(manifest_path),
            },
            ensure_ascii=True,
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
